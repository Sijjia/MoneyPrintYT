"""Анти-нейрослоп: RU-ориентированная библиотека маркеров + скорер.
Основано на маркерах из ru.wikipedia «Признаки сгенерированности текста», en Wikipedia
«Signs of AI writing» и ресёрча блоклистов. Идея: слоп = ПЛОТНОСТЬ сигналов, не один хит.

Ключевые метрики:
  • фраза-блоклист (шаблоны-штампы, negative parallelism, значимость-концовки) — жёсткие хиты;
  • «пустые» предложения-осмысления (нет ни цифры, ни имени собственного + глагол-значимости);
  • плотность инфляционных слов/хеджей; правило трёх; разброс длины предложений; тире.
Экспортит: split_sentences, flag_sentence, score_text.
"""
import re

# --- 1. ФРАЗА-БЛОКЛИСТ (жёсткие шаблоны-штампы) ---
PHRASE_PATTERNS = [
    # negative parallelism (RU) — самый характерный ИИ-оборот
    (r"\bне просто\b[^.!?]{0,70}\bа\b", "негатив-параллелизм «не просто…а»"),
    (r"\bне только\b[^.!?]{0,70}\bно и\b", "негатив-параллелизм «не только…но и»"),
    (r"\bэто не\b[^.!?]{0,40}\bэто\b", "«это не X, это Y»"),
    # значимость-штампы (пустой пафос)
    (r"неизгладим\w+ след", "штамп «неизгладимый след»"),
    (r"поворотн\w+ момент", "штамп «поворотный момент»"),
    (r"served? как напоминани|служ\w+ напоминани", "штамп «служит напоминанием»"),
    (r"навсегда измени\w+", "штамп «навсегда изменил»"),
    (r"вош\w+ в историю", "штамп «вошёл в историю»"),
    (r"ста\w+ символ\w+", "штамп «стал символом»"),
    (r"символизир\w+", "штамп «символизирует»"),
    (r"олицетворя\w+", "штамп «олицетворяет»"),
    (r"сыгра\w+ (ключев\w+|важн\w+|решающ\w+) роль", "штамп «сыграл ключевую роль»"),
    (r"оставил\w? (глубок\w+|заметн\w+)? ?след", "штамп «оставил след»"),
    (r"це\w+ю эпоху|целой эпохи|нову\w+ эпоху|наступлени\w+ эпохи", "штамп «эпоха»"),
    (r"(богат\w+|важн\w+) наследи", "штамп «наследие»"),
    (r"изменил\w? (ход|облик|ландшафт|мир)", "штамп «изменил ход/облик»"),
    (r"последстви\w+ (был\w+ )?(ошеломл\w+|колоссальн\w+|катастрофическ\w+)", "штамп «последствия ошеломляющие»"),
    # значимость-хвосты (деепричастные обороты значимости)
    (r",\s*(подчёрк\w+|символизир\w+|знаменуя|закрепляя|отражая|превраща\w+ .{0,25} в|делая (его|её|это)|цементир\w+)", "хвост-значимость (деепричастие)"),
    # сцена-сеттеры / канцелярит-зачины
    (r"\bв мире,? где\b", "зачин «в мире, где»"),
    (r"\bв (эпоху|эру),? когда\b", "зачин «в эпоху, когда»"),
    (r"\bпредставьте( себе)?\b", "зачин «представьте»"),
    (r"\bвообразите\b", "зачин «вообразите»"),
    (r"(?:^|[.!?…]\s+)что,?\s+если\b|что,? если я скажу", "зачин «что если»"),
    (r"\bдавайте (разбер|погруз|начн)\w+", "зачин «давайте разберёмся»"),
    # зазывалки-переходы
    (r"\bпогружаемся\b", "зазывалка «погружаемся»"),
    (r"\bспуска\w+ся (глубже|ниже)\b", "зазывалка «спускаемся глубже»"),
    (r"\bид[её]м (дальше|глубже)\b", "зазывалка «идём дальше»"),
    (r"\bдобро пожаловать\b", "зазывалка «добро пожаловать»"),
    (r"\bприготовьтесь\b", "зазывалка «приготовьтесь»"),
    # фейк-саспенс
    (r"\bмало кто зна\w+\b", "фейк-саспенс «мало кто знал»"),
    (r"\bно (всё|это) (вот-вот|скоро)? ?(измени\w+|должно было измени\w+)\b", "фейк-саспенс «но всё изменилось»"),
    (r"\bи (вот )?тогда\b", "фейк-саспенс «и вот тогда»"),
    (r"\bили так (им )?казалось\b", "фейк-саспенс «или так казалось»"),
    (r"\bчто (было|случилось) дальше\b", "фейк-саспенс «что случилось дальше»"),
    # дидактические оговорки
    (r"\bважно (отметить|понимать|помнить)\b", "оговорка «важно отметить»"),
    (r"\bстоит (отметить|учитывать|помнить)\b", "оговорка «стоит отметить»"),
    # риторический вопрос + мгновенный ответ
    (r"[?]\s+(потому что|дело в том|ответ|оказыва\w+|да\.|нет\.|всё просто)", "риторич.вопрос+ответ"),
    # чат-бот остаток
    (r"\bнадеюсь,? это помог\w+\b|\bкак мы (уже )?видели\b|\bконечно!\b", "чат-бот остаток"),
]

# --- 2. ИНФЛЯЦИОННЫЕ СЛОВА / ХЕДЖИ (плотность, не одиночный бан) ---
INFLATED = [
    "мощный", "мощнейш", "яркий", "ярчайш", "богатый", "потрясающ", "невероятн",
    "поразительн", "ошеломля", "грандиозн", "колоссальн", "легендарн", "культов",
    "знаковый", "беспрецедентн", "уникальн", "судьбоносн", "монументальн", "феноменальн",
]
HEDGES = [
    "поистине", "по-настоящему", "буквально", "пожалуй", "во многом", "в каком-то смысле",
    "по сути", "фактически", "как известно", "безусловно", "несомненно", "разумеется",
]
TRANSITIONS = [
    "более того", "кроме того", "к тому же", "таким образом", "в конечном счёте",
    "в конечном итоге", "стоит отметить", "примечательно", "следовательно",
]

# глаголы-значимости (для детекции «пустых» предложений)
SIGNIF_VERBS = re.compile(
    r"(символизир|олицетвор|знамену|воплоща|отража\w+ (эпоху|дух)|стал\w? символ|"
    r"навсегда измен|вош\w+ в историю|оставил\w? .{0,15}след|сыгра\w+ .{0,10}роль|"
    r"поворотн\w+ момент|це\w+ эпох|наследи|последстви\w+ .{0,20}(ошелом|колосс))", re.I)

# «конкретика» — если есть, предложение НЕ пустое
HAS_CONCRETE = re.compile(r"\d|[«\"“][^»\"”]+[»\"”]|[A-Z][a-zA-Z]{2,}|[А-ЯЁ][а-яё]{3,}\s+[А-ЯЁ]")


def split_sentences(text):
    # убираем markdown-заголовки и метки паузы для анализа тела
    body = re.sub(r"(?m)^#{1,6}\s.*$", "", text)
    body = re.sub(r"\[пауза[^\]]*\]", "", body)
    sents = re.split(r"(?<=[.!?…])\s+", body)
    return [s.strip() for s in sents if len(s.strip()) > 1]


def flag_sentence(s):
    """→ список причин (маркеров), почему предложение похоже на слоп."""
    low = s.lower()
    hits = []
    for pat, name in PHRASE_PATTERNS:
        if re.search(pat, low):
            hits.append(name)
    # инфляционные/хеджи/переходы-открывашки
    infl = sum(1 for w in INFLATED if w in low)
    hedg = sum(1 for w in HEDGES if w in low)
    if infl >= 2:
        hits.append(f"инфляц.прилагательные×{infl}")
    if hedg >= 1:
        hits.append("хедж")
    if any(low.startswith(t) for t in TRANSITIONS):
        hits.append("переход-открывашка")
    # правило трёх: три прилагательных/однородных через запятую перед «и»
    if re.search(r"\b\w+(?:ый|ий|ой|ая|яя|ое|ее|ые|ие),\s+\w+(?:ый|ий|ой|ая|яя|ое|ее|ые|ие),?\s+и\s+\w+(?:ый|ий|ой|ая|яя|ое|ее|ые|ие)\b", low):
        hits.append("правило-трёх")
    # «пустое» предложение: глагол-значимости и НЕТ конкретики
    if SIGNIF_VERBS.search(low) and not HAS_CONCRETE.search(s):
        hits.append("ПУСТОЕ (значимость без факта)")
    return hits


def score_text(text):
    sents = split_sentences(text)
    n = max(1, len(sents))
    flagged, empties, emdash, lens = [], 0, 0, []
    for s in sents:
        h = flag_sentence(s)
        lens.append(len(s.split()))
        emdash += s.count("—")
        if any("ПУСТОЕ" in x for x in h):
            empties += 1
        if h:
            flagged.append((s, h))
    words = sum(lens)
    mean = words / n
    var = (sum((l - mean) ** 2 for l in lens) / n) ** 0.5
    return {
        "sentences": n,
        "words": words,
        "flagged": flagged,
        "flagged_pct": round(100 * len(flagged) / n, 1),
        "empty_pct": round(100 * empties / n, 1),
        "emdash_per_1k": round(1000 * emdash / max(1, words), 1),
        "len_stdev": round(var, 1),
    }
