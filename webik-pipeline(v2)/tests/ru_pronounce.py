# компиляция: границы слова, регистронезависимо по латинице
_COMPILED = [(re.compile(r"(?<![A-Za-zА-Яа-яЁё0-9])" + re.escape(lat) + r"(?![A-Za-zА-Яа-яЁё0-9])", re.I), cyr)
             for lat, cyr in MAP]


def normalize(text: str) -> str:
    """Заменяет латинские названия на кириллическую фонетику (для TTS). scenes.json НЕ трогать — только речь."""
    for pat, cyr in _COMPILED:
        text = pat.sub(cyr, text)
    return text


