"""
services/research/web_research.py
Веб-ресёрч темы перед Stage 1 — чтобы айсберг строился на РЕАЛЬНЫХ фактах
(особенно для хайповых/свежих тем, которых нет в знаниях модели до cutoff).

Использует OpenRouter `:online` (модель + веб-поиск) — добавляет к LLM свежие
результаты из интернета с источниками. Возвращает структурированный дайджест
фактов, который Stage 1 кладёт в промпт концепции.

Требует провайдера OpenRouter (`:online` — его фича). На прямом Anthropic-ключе
вернёт "" (веб-поиск недоступен) — пайплайн просто работает как раньше.
"""
from typing import Optional

from core.config import get_settings
from core.logger import setup_logger
from services.llm.claude import ClaudeService

log = setup_logger("web-research")


_PROMPT = """Ты — ресёрчер для русскоязычного YouTube-канала про «айсберги» (тёмные, загадочные, малоизвестные темы с погружением от поверхности к бездне).

ТЕМА РОЛИКА: {idea}

Используя ВЕБ-ПОИСК, собери РЕАЛЬНЫЕ факты для будущего сценария. Нужно:
- ключевые события, даты, имена, цифры, географию — конкретику, а не общие слова;
- малоизвестные детали и «крючки», которые цепляют;
- теории, слухи, версии — но ПОМЕЧАЙ их как слух/версию, не выдавай за факт;
- если тема актуальная/хайповая — самые свежие новости и развитие событий;
- спорные и тёмные стороны темы (для глубоких уровней айсберга).

Структурируй по нарастанию глубины: от общеизвестного → к странному → к тёмному/спорному.
Только проверяемые факты и явно помеченные слухи. Без воды и философии.
Где факт важный или свежий — укажи источник в скобках.
Объём — насыщенный конспект (не эссе), которого хватит на сценарий 25-30 минут."""


def research_topic(idea: str, *, max_tokens: int = 3000) -> str:
    """Возвращает дайджест фактов по теме из веб-поиска. "" если недоступно."""
    s = get_settings()
    if not s.openrouter_api_key:
        log.info("Веб-ресёрч доступен только через OpenRouter (:online) — пропускаю")
        return ""

    base = (s.llm_model or "anthropic/claude-sonnet-4.5").split(":")[0]
    model = f"{base}:online"
    try:
        c = ClaudeService(model=model)
        digest = c.call(_PROMPT.format(idea=idea), max_tokens=max_tokens, temperature=0.3)
        log.info(f"Веб-ресёрч готов: {len(digest)} символов (модель {model})")
        return digest.strip()
    except Exception as e:
        log.warning(f"Веб-ресёрч не удался ({str(e)[:160]}) — продолжаю без него")
        return ""
