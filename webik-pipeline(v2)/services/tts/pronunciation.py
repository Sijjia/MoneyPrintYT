"""Лексикон произношения для ElevenLabs (русский).

ElevenLabs по-русски уважает знак ударения — комбинирующий акут U+0301 после
ударной гласной («Грабово́й»). Применяем к тексту ПЕРЕД синтезом (не трогая
scenes.json, чтобы не ломать привязку графики по тексту).

Добавляй сюда слова/имена, которые диктор произносит с неправильным ударением
(Айдар слушает и называет). Ключ — форма как в тексте (регистронезависимо по
первой букве не важно, matching по точной подстроке-слову), значение — с ударением.
"""
import re

A = "́"  # combining acute (ударение)

# слово (в нижнем регистре, по основам-формам) → версия с ударением
LEXICON = {
    "грабовой": f"Грабов{A}ой",
    "грабового": f"Грабов{A}ого",
    "грабовому": f"Грабов{A}ому",
    "грабовым": f"Грабов{A}ым",
    "грабове": f"Грабов{A}е",
}


def apply_pronunciation(text: str, lexicon: dict | None = None) -> str:
    """Подставляет ударения по словарю (по границам слов, регистр сохраняем условно)."""
    lex = lexicon or LEXICON
    if not lex:
        return text
    # \w с юникодом; заменяем целые слова
    def repl(m: re.Match) -> str:
        w = m.group(0)
        fixed = lex.get(w.lower())
        return fixed if fixed else w
    pat = re.compile(r"[А-Яа-яЁё]+")
    return pat.sub(repl, text)
